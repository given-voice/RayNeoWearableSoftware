"""Turns audio_src/phrase_NNN_*.mp3 (the ElevenLabs audio cached by the app) into audio_data.h.

The ESP32 plays these straight from flash, so the speaker box works without the glasses
generating audio. Re-run after phrases change (pull the new files from the glasses first):

    adb exec-out run-as com.givenvoice.wearable cat files/tts/<file>.mp3 > audio_src/<file>.mp3

    python make_audio_data.py
"""
import re
from pathlib import Path

HERE = Path(__file__).parent
SRC = HERE / "audio_src"
OUT = HERE / "switch_audio" / "audio_data.h"


def strip_id3(data: bytes) -> bytes:
    """Drop the ID3v2 tag at the start (the decoder only needs the MPEG frames)."""
    if data[:3] == b"ID3":
        size = (data[6] << 21) | (data[7] << 14) | (data[8] << 7) | data[9]
        return data[10 + size:]
    return data


def main() -> None:
    phrases = {}
    for f in sorted(SRC.glob("phrase_*.mp3")):
        match = re.match(r"phrase_(\d+)_", f.name)
        if match:
            phrases[int(match.group(1))] = strip_id3(f.read_bytes())
    if not phrases:
        raise SystemExit(f"No phrase_*.mp3 files in {SRC}")

    top = max(phrases)
    OUT.parent.mkdir(exist_ok=True)
    with OUT.open("w", newline="\n") as out:
        out.write("// Generated by make_audio_data.py - do not edit.\n#pragma once\n#include <stdint.h>\n#include <stddef.h>\n\n")
        for pid, data in sorted(phrases.items()):
            out.write(f"static const uint8_t PHRASE_{pid}[] = {{\n")
            for i in range(0, len(data), 24):
                out.write(",".join(str(b) for b in data[i:i + 24]) + ",\n")
            out.write("};\n")
        out.write(f"\nstatic const int PHRASE_MAX_ID = {top};\n")
        out.write("static const uint8_t* const PHRASE_DATA[] = {\n  nullptr,\n")
        for pid in range(1, top + 1):
            out.write(f"  PHRASE_{pid}," if pid in phrases else "  nullptr,")
            out.write("\n")
        out.write("};\nstatic const size_t PHRASE_LEN[] = {\n  0,\n")
        for pid in range(1, top + 1):
            out.write(f"  sizeof(PHRASE_{pid})," if pid in phrases else "  0,")
            out.write("\n")
        out.write("};\n")
    total = sum(len(d) for d in phrases.values())
    print(f"{len(phrases)} phrases, {total / 1024:.0f} KB of audio -> {OUT}")


if __name__ == "__main__":
    main()
